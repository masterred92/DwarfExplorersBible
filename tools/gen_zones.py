#!/usr/bin/env python3
"""Writes Zones.lua: every Forever zone map (UiMap Type 3) with its continent and world-space centre, plus the
gathering spells (SpellName "Herbalism"/"Herb Gathering"/"Mining"/"Skinning" among Data.lua's lootCasts).

usage: gen_zones.py <maps csv dir: UiMap.csv, UiMapAssignment.csv> <SpellName.csv> <build> [--out Zones.lua]
The centre is the middle of the zone's UiMapAssignment world Region (yards), so distances between zones on one
continent are real distances. Nothing is hand-entered.
"""
import csv, re, sys, pathlib

args = sys.argv[1:]
out = "Zones.lua"
if "--out" in args:
    i = args.index("--out"); out = args[i + 1]; del args[i:i + 2]
maps, spellcsv, build = pathlib.Path(args[0]), args[1], args[2]
um = {r["ID"]: r for r in csv.DictReader(open(maps / "UiMap.csv", encoding="utf-8"))}
asg = list(csv.DictReader(open(maps / "UiMapAssignment.csv", encoding="utf-8")))
zones = []
seen = set()
for zid, r in sorted(um.items(), key=lambda x: int(x[0])):
    if r["Type"] != "3" or r["Name_lang"] in seen:
        continue
    rows = [a for a in asg if a["UiMapID"] == zid and a["OrderIndex"] == "0"]
    if not rows:
        continue
    a = rows[0]
    x = (float(a["Region_0"]) + float(a["Region_3"])) / 2
    y = (float(a["Region_1"]) + float(a["Region_4"])) / 2
    seen.add(r["Name_lang"])
    zones.append((r["Name_lang"], int(zid), int(a["MapID"]), round(x), round(y)))

data = pathlib.Path(__file__).resolve().parent.parent / "Data.lua"
blk = data.read_text(encoding="utf-8")
blk = blk[blk.index("lootCasts = {"):]
blk = blk[:blk.index("},")]
loot = {int(k) for k in re.findall(r"\[(\d+)\] =", blk)}
KIND = {"Herbalism": "herb", "Herb Gathering": "herb", "Mining": "mine", "Skinning": "skin"}
gather = {}
for row in csv.reader(open(spellcsv, encoding="utf-8")):
    if row and row[0].isdigit() and int(row[0]) in loot and row[1] in KIND:
        gather[int(row[0])] = KIND[row[1]]

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

lines = [f"-- GENERATED by tools/gen_zones.py from WoW: Forever {build} UiMap, UiMapAssignment and SpellName (wago.tools, product wowf). Do not edit by hand.",
         "-- zones[name] = { map = uiMapID, cont = world map ID, x, y = centre of the zone in world yards }.",
         "-- gatherSpells[spellID] = herb | mine | skin (the gathering casts among Data.lootCasts).",
         "local _, ns = ...",
         "ns.Zones = {",
         f"  build = {lua_str(build)},",
         "  zones = {"]
for name, zid, cont, x, y in zones:
    lines.append(f"    [{lua_str(name)}] = {{ map = {zid}, cont = {cont}, x = {x}, y = {y} }},")
lines += ["  },", "  gatherSpells = {"]
for sid in sorted(gather):
    lines.append(f"    [{sid}] = \"{gather[sid]}\",")
lines += ["  },", "}", ""]
pathlib.Path(out).write_text("\n".join(lines), encoding="utf-8")
print(f"{len(zones)} zones, {len(gather)} gathering spells -> {out}")
