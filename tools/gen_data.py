#!/usr/bin/env python3
"""Builds Data.lua from nexus-devs/wow-classic-items (MIT) data/json/data.json.
Usage: tools/gen_data.py path/to/data.json"""
import json, sys
d = json.load(open(sys.argv[1]))
byid = {i["itemId"]: i for i in d}
VANILLA_MAX_ID, LATER = 23900, {"Inscription", "Jewelcrafting"}
profs = sorted({c["category"] for i in d for c in i.get("createdBy") or []} - LATER)
rows, used = [], set()
for i in sorted(d, key=lambda x: x["itemId"]):
    for c in i.get("createdBy") or []:
        # Vanilla only (Forever is a 1.x client): no TBC+ items, professions or skill above 300.
        if not c.get("reagents") or i["itemId"] > VANILLA_MAX_ID or c["category"] in LATER: continue
        if (c.get("requiredSkill") or 0) > 300 or any(r["itemId"] > VANILLA_MAX_ID for r in c["reagents"]): continue
        a = c.get("amount") or [1, 1]
        rec = (c.get("recipes") or [0])[0] or 0
        rg = ",".join(f'{r["itemId"]}:{r["amount"]}' for r in c["reagents"])
        rows.append(f'"{i["itemId"]};{a[0]};{a[-1]};{profs.index(c["category"]) + 1};{c.get("requiredSkill") or 0};{rec};{rg}"')
        used.add(i["itemId"]); used.update(r["itemId"] for r in c["reagents"])
def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["-- GENERATED by tools/gen_data.py. Do not edit by hand.",
 "-- Recipe data from nexus-devs/wow-classic-items (MIT, https://github.com/nexus-devs/wow-classic-items).",
 "-- Row: product;minQty;maxQty;profession;requiredSkill;recipeItem;reagent:count,...",
 "local _, ns = ...", "ns.Data = {", "  professions = { " + ", ".join(q(p) for p in profs) + " },", "  recipes = {"]
out += ["    " + r + "," for r in rows]
out += ["  },", "  names = {"]
out += [f"    [{k}] = {q(byid[k]['name'])}," for k in sorted(used) if k in byid]
out += ["  },", "  vendor = {"]
out += [f"    [{k}] = {byid[k]['sellPrice']}," for k in sorted(used) if k in byid and byid[k].get("sellPrice")]
out += ["  },", "}"]
open("Data.lua", "w").write("\n".join(out) + "\n")
print(len(rows), "recipes,", len(used), "items,", profs)
