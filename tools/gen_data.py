#!/usr/bin/env python3
"""Builds Data.lua from WoW: Forever's own client tables (DB2 CSVs for product `wowf`, build 1.60.1.70862,
exported from https://wago.tools/db2/<Table>/csv?product=wowf&build=1.60.1.70862).
Usage: tools/gen_data.py <dir with SkillLineAbility, SpellEffect, SpellReagents, ItemSparse .csv> [wow-classic-items data.json]
The optional data.json (nexus-devs/wow-classic-items, MIT) only marks which reagents a vendor sells."""
import csv, json, sys, os
src = sys.argv[1]
def rows(t): return csv.DictReader(open(os.path.join(src, t + ".csv"), encoding="utf-8"))
SKILL = {"171": "Alchemy", "164": "Blacksmithing", "185": "Cooking", "333": "Enchanting", "202": "Engineering",
         "129": "First Aid", "165": "Leatherworking", "186": "Mining", "197": "Tailoring"}
profs = sorted(set(SKILL.values()))
create = {}
for r in rows("SpellEffect"):  # effect 24 = SPELL_EFFECT_CREATE_ITEM
    if r["Effect"] == "24" and r["EffectItemType"] != "0":
        create.setdefault(r["SpellID"], (int(r["EffectItemType"]), max(1, int(round(float(r["EffectBasePointsF"] or 1))))))
reag = {}
for r in rows("SpellReagents"):
    reag[r["SpellID"]] = [(int(r[f"Reagent_{i}"]), int(r[f"ReagentCount_{i}"])) for i in range(8)
                          if r[f"Reagent_{i}"] != "0" and int(r[f"ReagentCount_{i}"] or 0) > 0]
items = {int(r["ID"]): r for r in rows("ItemSparse")}
out_rows, used, seen = [], set(), set()
for r in sorted(rows("SkillLineAbility"), key=lambda r: int(r["Spell"])):
    sp = r["Spell"]
    # TradeSkillCategoryID 0 = not shown in Forever's profession window (unused/test rows).
    if r["SkillLine"] not in SKILL or r["TradeSkillCategoryID"] == "0" or sp not in create or not reag.get(sp): continue
    pid, n = create[sp]
    if pid not in items or (pid, sp) in seen: continue
    seen.add((pid, sp))
    y, g = int(r["TrivialSkillLineRankLow"] or 0), int(r["TrivialSkillLineRankHigh"] or 0)
    rg = ",".join(f"{i}:{c}" for i, c in reag[sp])
    out_rows.append((pid, f'"{pid};{n};{n};{profs.index(SKILL[r["SkillLine"]]) + 1};{y};{g};{sp};{rg}"'))
    used.add(pid); used.update(i for i, _ in reag[sp])
out_rows.sort()
vendor_sold = set()
if len(sys.argv) > 2:
    vendor_sold = {i["itemId"] for i in json.load(open(sys.argv[2])) if i.get("vendorPrice")}
def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["-- GENERATED by tools/gen_data.py from WoW: Forever 1.60.1.70862 client tables (wago.tools, product wowf). Do not edit by hand.",
       "-- Row: product;minQty;maxQty;profession;yellowAt;greyAt;spellID;reagent:count,...",
       "-- buy = vendor price per unit (Forever ItemSparse BuyPrice / VendorStackCount) for reagents sold by vendors.",
       "local _, ns = ...", "ns.Data = {", "  professions = { " + ", ".join(q(p) for p in profs) + " },", "  recipes = {"]
out += ["    " + r + "," for _, r in out_rows]
out += ["  },", "  names = {"]
out += [f"    [{k}] = {q(items[k]['Display_lang'])}," for k in sorted(used) if k in items]
out += ["  },", "  buy = {"]
for k in sorted(used):
    it = items.get(k)
    if k in vendor_sold and it and int(it["BuyPrice"] or 0) > 0:
        out.append(f"    [{k}] = {max(1, round(int(it['BuyPrice']) / max(1, int(it['VendorStackCount'] or 1))))},")
out += ["  },", "}"]
open("Data.lua", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(out_rows), "recipes,", len(used), "items")
