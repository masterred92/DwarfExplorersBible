#!/usr/bin/env python3
"""Build BaselinePrices.lua from a Forever auction-price snapshot JSON.

Usage: tools/gen_baseline_prices.py <snapshot.json> [--out BaselinePrices.lua]

The snapshot has { market, capturedAt (unix seconds), prices: { itemID: { p, qty, at } or copper } }.
Only positive integer copper values are written, sorted by numeric itemID. This is the lowest-priority
price source in Prices.lua: any live PriceLog, Auctionator, TSM, Auctioneer or DEB scan price beats it.
"""
import argparse, json, os, sys
from datetime import datetime, timezone

ap = argparse.ArgumentParser()
ap.add_argument("src", help="Forever price snapshot JSON (market, capturedAt, prices)")
ap.add_argument("--out", default="BaselinePrices.lua")
args = ap.parse_args()

with open(args.src, encoding="utf-8") as f:
    data = json.load(f)

market = data.get("market")
captured = data.get("capturedAt")
raw = data.get("prices")
if not isinstance(market, str) or not market:
    sys.exit("snapshot is missing a market string")
if not isinstance(captured, int) or captured <= 0:
    sys.exit("snapshot capturedAt must be a positive unix-seconds integer")
if not isinstance(raw, dict):
    sys.exit("snapshot is missing a prices object")

prices = []
for key, rec in raw.items():
    try:
        item_id = int(key)
    except (TypeError, ValueError):
        sys.exit("non-integer itemID %r" % (key,))
    if item_id <= 0:
        sys.exit("non-positive itemID %s" % item_id)
    copper = rec.get("p") if isinstance(rec, dict) else rec
    if not isinstance(copper, int) or isinstance(copper, bool) or copper <= 0:
        continue
    prices.append((item_id, copper))

prices.sort()
if not prices:
    sys.exit("no positive integer copper prices in %s" % args.src)

day = datetime.fromtimestamp(captured, timezone.utc).strftime("%Y-%m-%d")
src_name = os.path.basename(args.src)

lines = [
    "-- GENERATED by tools/gen_baseline_prices.py from %s. Do not edit by hand." % src_name,
    "-- %d crafting-reagent prices; market %s; captured %s (unix %d)." % (len(prices), market, day, captured),
    "-- Lowest-priority source in Prices.lua: any live PriceLog, Auctionator, TSM, Auctioneer or DEB scan price beats these.",
    "local _, ns = ...",
    "ns.BaselinePrices = {",
    "  market = %s," % json.dumps(market),
    "  capturedAt = %d," % captured,
    "  prices = {",
]
for item_id, copper in prices:
    lines.append("    [%d] = %d," % (item_id, copper))
lines.append("  },")
lines.append("}")
lines.append("")

text = "\n".join(lines)
with open(args.out, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)

print("wrote %s: %d prices, market=%s, capturedAt=%d (%s)" % (args.out, len(prices), market, captured, day))
